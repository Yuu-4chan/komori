/// -ar verbs (`v_ar`).
pub(crate) const V_AR: u32 = 1;
/// -er verbs (`v_er`).
pub(crate) const V_ER: u32 = 1 << 1;
/// -ir verbs (`v_ir`).
pub(crate) const V_IR: u32 = 1 << 2;
/// Verbs (`v`).
pub(crate) const V: u32 = V_AR | V_ER | V_IR;
/// Singular nouns (`ns`).
pub(crate) const NS: u32 = 1 << 3;
/// Plural nouns (`np`).
pub(crate) const NP: u32 = 1 << 4;
/// Nouns (`n`).
pub(crate) const N: u32 = NS | NP;
/// Adjectives (`adj`).
pub(crate) const ADJ: u32 = 1 << 5;
/// The word classes a term's rules can name.
pub(crate) const DICTIONARY_FORMS: u32 = V | N | ADJ;

/// The word classes a term's space-separated rules name.
pub(crate) fn word_classes(rules: &str) -> u32 {
    named_classes(rules, &[("v", V), ("n", N), ("adj", ADJ)])
}

