//! The Spanish deinflection rules: Yomitan's Spanish transforms (the simple tenses with their
//! stem changes, participles, reflexive verbs, noun plurals and feminine adjectives), translated
//! to Rust, followed by Komori's own rules for what they leave out: pronouns joined to an
//! infinitive or gerund, adjective plurals, diminutives, superlatives and adverbs in -mente.
//! Yomitan's pronominal rule (me despertar → despertarse) spans two words and is left out.

