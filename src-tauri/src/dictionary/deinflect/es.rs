/// Komori's rules after Yomitan's.
static KOMORI: LazyLock<Vec<Rule>> = LazyLock::new(|| {
    let mut rules = Vec::new();
    for (ending, accented, base) in [
        ("ar", "ár", V_AR),
        ("er", "ér", V_ER),
        ("ir", "ír", V_IR),
        ("ando", "ándo", V_AR),
        ("iendo", "iéndo", V_ER | V_IR),
    ] {
        rules.extend(super::endings(PRONOUN, ending, PRONOUNS, ending, 0, base));
        rules.extend(super::endings(
            PRONOUN,
            accented,
            PRONOUN_PAIRS,
            ending,
            0,
            base,
        ));
        if ending.ends_with("do") {
            rules.extend(super::endings(PRONOUN, accented, PRONOUNS, ending, 0, base));
        }
    }
    rules.extend([
        rule(PLURAL, "s", "", ADJ, ADJ),
        rule(PLURAL, "es", "", ADJ, ADJ),
        rule(DIMINUTIVE, "ito", "o", N | ADJ, N | ADJ),
        rule(DIMINUTIVE, "ita", "a", N | ADJ, N | ADJ),
        rule(DIMINUTIVE, "cito", "", N | ADJ, N | ADJ),
        rule(DIMINUTIVE, "cita", "", N | ADJ, N | ADJ),
        rule(SUPERLATIVE, "ísimo", "o", ADJ, ADJ),
        rule(SUPERLATIVE, "ísimo", "e", ADJ, ADJ),
        rule(SUPERLATIVE, "ísima", "a", ADJ, ADJ),
        rule(ADVERB, "mente", "", 0, ADJ),
    ]);
    rules
});

static RULES: LazyLock<RuleSet<'static>> = LazyLock::new(|| RuleSet::new(YOMITAN, &KOMORI));

/// The forms `text` may be an inflection of (see `deinflect_bounded`).
pub(crate) fn deinflect(text: &str) -> Vec<Candidate> {
    deinflect_bounded(text, &RULES, MAX_STEPS, MAX_CANDIDATES)
}

