//! The French deinflection rules: Yomitan's French transforms (the simple tenses of the three
//! verb groups and être/avoir, and noun plurals), translated to Rust, followed by Komori's own
//! rules for what they leave out: past participles, adjectives' feminine and plural forms and
//! adverbs in -ment. Compound tenses are two words, so their participle is looked up on its own.

use std::sync::LazyLock;

use super::{
    deinflect_bounded, named_classes, rule, Candidate, Rule, RuleSet, MAX_CANDIDATES, MAX_STEPS,
};

/// Verbs (`v`).
pub(crate) const V: u32 = 1;
/// Nouns (`n`).
pub(crate) const N: u32 = 1 << 1;
/// Adjectives (`adj`).
pub(crate) const ADJ: u32 = 1 << 2;
/// Adverbs (`adv`).
pub(crate) const ADV: u32 = 1 << 3;
/// The auxiliaries être and avoir (`aux`).
pub(crate) const AUX: u32 = 1 << 4;
/// The word classes a term's rules can name.
pub(crate) const DICTIONARY_FORMS: u32 = V | N | ADJ | ADV | AUX;

/// The word classes a term's space-separated rules name.
pub(crate) fn word_classes(rules: &str) -> u32 {
    named_classes(
        rules,
        &[("v", V), ("n", N), ("adj", ADJ), ("adv", ADV), ("aux", AUX)],
    )
}

