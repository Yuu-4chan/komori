//! Catalog-scoped, read-only handoff for an archived EPUB renderer.

use std::{
    fs::File,
    io::{Read, Seek, SeekFrom},
    path::Path,
};

use rusqlite::{Connection, OpenFlags, OptionalExtension};
use serde::Serialize;
use tauri::{
    http::{header, Method, Request, Response, StatusCode},
    Manager, State, UriSchemeContext, UriSchemeResponder, Wry,
};
use uuid::Uuid;

use crate::{epub, library::CatalogState};

const SCHEME: &str = "komori-book";
const MIME: &str = "application/epub+zip";
// Tauri's protocol response owns one byte buffer; cap its peak native allocation.
const MAX_EPUB_BYTES: u64 = 512 * 1024 * 1024;

#[derive(Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ContentAccess {
    status: ContentStatus,
    url: Option<String>,
}

#[derive(Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
enum ContentStatus {
    Ready,
    Unknown,
    Missing,
    Unreadable,
    Invalid,
    TooLarge,
    Failed,
}

impl ContentAccess {
    fn failure(status: ContentStatus) -> Self {
        Self { status, url: None }
    }
}

#[tauri::command]
pub async fn prepare_book_content(
    catalog: State<'_, CatalogState>,
    id: String,
) -> Result<ContentAccess, String> {
    let database = catalog.database.clone();
    let diagnostic_id = Uuid::parse_str(&id).ok();
    match tauri::async_runtime::spawn_blocking(move || prepare(&database, &id)).await {
        Ok(access) => Ok(access),
        Err(_) => {
            eprintln!(
                "{}",
                content_diagnostic(diagnostic_id, &ContentStatus::Failed)
            );
            Ok(ContentAccess::failure(ContentStatus::Failed))
        }
    }
}

fn prepare(database: &Path, id: &str) -> ContentAccess {
    match open_valid_source(database, id) {
        Ok(_) => ContentAccess {
            status: ContentStatus::Ready,
            url: Some(content_url(id)),
        },
        Err(status) => ContentAccess::failure(status),
    }
}

fn content_url(id: &str) -> String {
    // WebView2 maps custom schemes to a localhost origin on Windows and Android.
    if cfg!(any(target_os = "windows", target_os = "android")) {
        format!("http://{SCHEME}.localhost/{id}")
    } else {
        format!("{SCHEME}://localhost/{id}")
    }
}

/// Diagnostics contain only a validated catalog ID (or unknown) and a typed status.
fn content_diagnostic(id: Option<Uuid>, status: &ContentStatus) -> String {
    let id = id.map_or_else(|| "unknown".to_owned(), |id| id.to_string());
    format!("Komori Reader content {id}: {status:?}")
}

fn open_valid_source(database: &Path, id: &str) -> Result<File, ContentStatus> {
    // Catalog IDs are UUIDs generated by Komori. Reject path-shaped and malformed input first.
    let id = Uuid::parse_str(id).map_err(|_| ContentStatus::Unknown)?;
    let connection = Connection::open_with_flags(database, OpenFlags::SQLITE_OPEN_READ_ONLY)
        .map_err(|_| {
            eprintln!("{}", content_diagnostic(Some(id), &ContentStatus::Failed));
            ContentStatus::Failed
        })?;
    let source_path: Option<String> = connection
        .query_row(
            "SELECT source_path FROM books WHERE id = ?1",
            [id.to_string()],
            |row| row.get(0),
        )
        .optional()
        .map_err(|_| {
            eprintln!("{}", content_diagnostic(Some(id), &ContentStatus::Failed));
            ContentStatus::Failed
        })?;
    let source_path = source_path.ok_or(ContentStatus::Unknown)?;
    let source = File::open(&source_path).map_err(|error| {
        let status = if error.kind() == std::io::ErrorKind::NotFound {
            ContentStatus::Missing
        } else {
            ContentStatus::Unreadable
        };
        eprintln!("{}", content_diagnostic(Some(id), &status));
        status
    })?;
    match source.metadata() {
        Ok(metadata) if metadata.is_file() && metadata.len() > MAX_EPUB_BYTES => {
            return Err(ContentStatus::TooLarge);
        }
        Ok(metadata) if metadata.is_file() => {}
        Ok(_) => return Err(ContentStatus::Unreadable),
        Err(_) => {
            eprintln!(
                "{}",
                content_diagnostic(Some(id), &ContentStatus::Unreadable)
            );
            return Err(ContentStatus::Unreadable);
        }
    }
    // Validation reads only the bounded container and package documents; cover discovery
    // stays in the Library import path. It never writes the source or extracts a copy.
    let validation_file = source.try_clone().map_err(|_| {
        eprintln!(
            "{}",
            content_diagnostic(Some(id), &ContentStatus::Unreadable)
        );
        ContentStatus::Unreadable
    })?;
    epub::validate(validation_file).map_err(|_| {
        eprintln!("{}", content_diagnostic(Some(id), &ContentStatus::Invalid));
        ContentStatus::Invalid
    })?;
    Ok(source)
}

pub fn serve_book(
    context: UriSchemeContext<'_, Wry>,
    request: Request<Vec<u8>>,
    responder: UriSchemeResponder,
) {
    // The only current webview is the app-owned main Reader/Library window.
    if context.webview_label() != "main" {
        responder.respond(response(StatusCode::FORBIDDEN, Vec::new(), None));
        return;
    }
    let database = context
        .app_handle()
        .state::<CatalogState>()
        .database
        .clone();
    std::thread::spawn(move || responder.respond(handle_request(&database, &request)));
}

fn handle_request(database: &Path, request: &Request<Vec<u8>>) -> Response<Vec<u8>> {
    let origin = request
        .headers()
        .get(header::ORIGIN)
        .and_then(|value| value.to_str().ok())
        .filter(|origin| allowed_origin(origin));
    // A web page outside Komori cannot fetch or embed this protocol's content.
    if origin.is_none() || request.method() != Method::GET {
        return response(StatusCode::FORBIDDEN, Vec::new(), None);
    }
    let path = request.uri().path();
    let Some(id) = path.strip_prefix('/') else {
        return response(StatusCode::NOT_FOUND, Vec::new(), origin);
    };
    if Uuid::parse_str(id).is_err() || request.uri().query().is_some() {
        return response(StatusCode::NOT_FOUND, Vec::new(), origin);
    }
    let mut source = match open_valid_source(database, id) {
        Ok(source) => source,
        Err(status) => return response(http_status(status), Vec::new(), origin),
    };
    if source.seek(SeekFrom::Start(0)).is_err() {
        return response(StatusCode::FORBIDDEN, Vec::new(), origin);
    }
    // Size the buffer once so large books do not grow through repeated reallocations.
    let expected = source
        .metadata()
        .map_or(0, |metadata| metadata.len().min(MAX_EPUB_BYTES));
    let mut bytes = Vec::with_capacity(usize::try_from(expected).unwrap_or(0));
    if source
        .take(MAX_EPUB_BYTES + 1)
        .read_to_end(&mut bytes)
        .is_err()
    {
        return response(StatusCode::FORBIDDEN, Vec::new(), origin);
    }
    if bytes.len() as u64 > MAX_EPUB_BYTES {
        return response(StatusCode::PAYLOAD_TOO_LARGE, Vec::new(), origin);
    }
    response(StatusCode::OK, bytes, origin)
}

fn allowed_origin(origin: &str) -> bool {
    matches!(origin, "http://tauri.localhost" | "tauri://localhost")
        || (cfg!(debug_assertions) && origin == "http://127.0.0.1:1420")
}

fn http_status(status: ContentStatus) -> StatusCode {
    match status {
        ContentStatus::Ready => StatusCode::OK,
        ContentStatus::Unknown | ContentStatus::Missing => StatusCode::NOT_FOUND,
        ContentStatus::Unreadable => StatusCode::FORBIDDEN,
        ContentStatus::Invalid => StatusCode::UNPROCESSABLE_ENTITY,
        ContentStatus::TooLarge => StatusCode::PAYLOAD_TOO_LARGE,
        ContentStatus::Failed => StatusCode::INTERNAL_SERVER_ERROR,
    }
}

fn response(status: StatusCode, bytes: Vec<u8>, origin: Option<&str>) -> Response<Vec<u8>> {
    let mut builder = Response::builder()
        .status(status)
        .header(
            header::CONTENT_TYPE,
            if status == StatusCode::OK {
                MIME
            } else {
                "text/plain"
            },
        )
        .header(header::CACHE_CONTROL, "no-store")
        .header(header::X_CONTENT_TYPE_OPTIONS, "nosniff")
        .header("Vary", "Origin");
    if let Some(origin) = origin {
        builder = builder.header(header::ACCESS_CONTROL_ALLOW_ORIGIN, origin);
    }
    builder
        .body(bytes)
        .expect("static response headers are valid")
}

#[cfg(test)]
mod tests {
    use super::*;
    use sha2::{Digest, Sha256};
    use std::{fs, io::Write};
    use tempfile::tempdir;
    use zip::{write::SimpleFileOptions, CompressionMethod, ZipWriter};

    fn fixture(path: &Path, title: &str) {
        let file = File::create(path).unwrap();
        let mut archive = ZipWriter::new(file);
        let options = SimpleFileOptions::default().compression_method(CompressionMethod::Stored);
        archive
            .start_file("META-INF/container.xml", options)
            .unwrap();
        archive
            .write_all(br#"<?xml version="1.0"?><container><rootfiles><rootfile full-path="Nested/OPS/book.opf"/></rootfiles></container>"#)
            .unwrap();
        archive.start_file("Nested/OPS/book.opf", options).unwrap();
        archive
            .write_all(format!("<package xmlns:dc=\"http://purl.org/dc/elements/1.1/\"><metadata><dc:title>{title}</dc:title></metadata><manifest><item id=\"chapter\" href=\"Text/one.xhtml\" media-type=\"application/xhtml+xml\"/></manifest><spine><itemref idref=\"chapter\"/></spine></package>").as_bytes())
            .unwrap();
        archive
            .start_file("Nested/OPS/Text/one.xhtml", options)
            .unwrap();
        archive
            .write_all(b"<html><body>Fixture</body></html>")
            .unwrap();
        archive.finish().unwrap();
    }

    fn catalog(database: &Path, id: &str, source: &Path) {
        let connection = Connection::open(database).unwrap();
        connection
            .execute_batch("CREATE TABLE books (id TEXT PRIMARY KEY, source_path TEXT NOT NULL)")
            .unwrap();
        connection
            .execute(
                "INSERT INTO books (id, source_path) VALUES (?1, ?2)",
                rusqlite::params![id, source.to_string_lossy()],
            )
            .unwrap();
    }

    fn request(id: &str, origin: &str) -> Request<Vec<u8>> {
        Request::builder()
            .method(Method::GET)
            .uri(format!("http://komori-book.localhost/{id}"))
            .header(header::ORIGIN, origin)
            .body(Vec::new())
            .unwrap()
    }

    #[test]
    fn catalog_id_opens_nested_epub_as_binary_without_touching_source() {
        let directory = tempdir().unwrap();
        let source = directory.path().join("private.epub");
        let database = directory.path().join("library.sqlite3");
        let id = Uuid::new_v4().to_string();
        fixture(&source, "One");
        catalog(&database, &id, &source);
        let original = fs::read(&source).unwrap();
        let modified = source.metadata().unwrap().modified().unwrap();

        let access = prepare(&database, &id);
        assert_eq!(access.status, ContentStatus::Ready);
        assert_eq!(access.url.as_deref(), Some(content_url(&id).as_str()));
        assert!(!serde_json::to_string(&access)
            .unwrap()
            .contains("private.epub"));
        let served = handle_request(&database, &request(&id, "http://tauri.localhost"));
        assert_eq!(served.status(), StatusCode::OK);
        assert_eq!(served.headers()[header::CONTENT_TYPE], MIME);
        assert_eq!(served.body(), &original);
        assert_eq!(fs::read(&source).unwrap(), original);
        assert_eq!(source.metadata().unwrap().modified().unwrap(), modified);
    }

    #[test]
    fn recovered_package_is_served_unchanged_and_unknown_xml_is_refused() {
        let directory = tempdir().unwrap();
        let source = directory.path().join("recovered.epub");
        let database = directory.path().join("catalog.sqlite3");
        let id = Uuid::new_v4().to_string();
        crate::library::tests::tolerance_fixture(
            &source,
            crate::library::tests::MISSING_DC_PACKAGE,
        );
        catalog(&database, &id, &source);
        let before = fs::read(&source).unwrap();
        assert_eq!(prepare(&database, &id).status, ContentStatus::Ready);
        assert_eq!(
            handle_request(&database, &request(&id, "http://tauri.localhost")).body(),
            &before
        );
        assert_eq!(fs::read(&source).unwrap(), before);
        crate::library::tests::tolerance_fixture(
            &source,
            "<package version=\"3\"><other:title>Unknown</other:title></package>",
        );
        assert_eq!(prepare(&database, &id).status, ContentStatus::Invalid);
        assert_eq!(
            handle_request(&database, &request(&id, "http://tauri.localhost")).status(),
            StatusCode::UNPROCESSABLE_ENTITY
        );
    }

    #[test]
    fn diagnostics_contain_only_catalog_ids_and_typed_statuses() {
        let id = Uuid::nil();
        for (status, label) in [
            (ContentStatus::Unknown, "Unknown"),
            (ContentStatus::Missing, "Missing"),
            (ContentStatus::Unreadable, "Unreadable"),
            (ContentStatus::Invalid, "Invalid"),
            (ContentStatus::TooLarge, "TooLarge"),
            (ContentStatus::Failed, "Failed"),
        ] {
            assert_eq!(
                content_diagnostic(Some(id), &status),
                format!("Komori Reader content {id}: {label}")
            );
        }
        assert_eq!(
            content_diagnostic(
                Uuid::parse_str("../private-source.epub").ok(),
                &ContentStatus::Failed
            ),
            "Komori Reader content unknown: Failed"
        );
    }

    #[test]
    fn typed_failures_have_no_private_paths() {
        let directory = tempdir().unwrap();
        let source = directory.path().join("private-source.epub");
        let database = directory.path().join("library.sqlite3");
        let id = Uuid::new_v4().to_string();
        fixture(&source, "One");
        catalog(&database, &id, &source);

        assert_eq!(
            prepare(&database, &Uuid::new_v4().to_string()).status,
            ContentStatus::Unknown
        );
        assert_eq!(
            prepare(&database, "../private-source.epub").status,
            ContentStatus::Unknown
        );
        fs::remove_file(&source).unwrap();
        assert_eq!(prepare(&database, &id).status, ContentStatus::Missing);
        fs::create_dir(&source).unwrap();
        assert_eq!(prepare(&database, &id).status, ContentStatus::Unreadable);
        fs::remove_dir(&source).unwrap();
        fs::write(&source, b"not an EPUB").unwrap();
        assert_eq!(prepare(&database, &id).status, ContentStatus::Invalid);
        assert_eq!(
            prepare(&directory.path().join("missing.sqlite3"), &id).status,
            ContentStatus::Failed
        );
        for status in [
            ContentStatus::Unknown,
            ContentStatus::Missing,
            ContentStatus::Unreadable,
            ContentStatus::Invalid,
            ContentStatus::TooLarge,
            ContentStatus::Failed,
        ] {
            let encoded = serde_json::to_string(&ContentAccess::failure(status)).unwrap();
            assert!(!encoded.contains("private-source"));
            assert!(!encoded.contains("source_path"));
            assert!(encoded.contains("\"url\":null"));
        }
    }

    #[test]
    fn protocol_rejects_other_origins_methods_and_path_shapes() {
        let directory = tempdir().unwrap();
        let source = directory.path().join("book.epub");
        let database = directory.path().join("library.sqlite3");
        let id = Uuid::new_v4().to_string();
        fixture(&source, "One");
        catalog(&database, &id, &source);
        assert_eq!(
            handle_request(&database, &request(&id, "https://other.example")).status(),
            StatusCode::FORBIDDEN
        );
        let mut post = request(&id, "http://tauri.localhost");
        *post.method_mut() = Method::POST;
        assert_eq!(
            handle_request(&database, &post).status(),
            StatusCode::FORBIDDEN
        );
        for bad in ["..%2Fbook.epub", "not-a-catalog-id", "book.epub"] {
            assert_eq!(
                handle_request(&database, &request(bad, "http://tauri.localhost")).status(),
                StatusCode::NOT_FOUND
            );
        }
    }

    #[test]
    fn every_fetch_resolves_current_catalog_reference_without_a_stale_handle() {
        let directory = tempdir().unwrap();
        let first = directory.path().join("first.epub");
        let second = directory.path().join("second.epub");
        let database = directory.path().join("library.sqlite3");
        let id = Uuid::new_v4().to_string();
        fixture(&first, "One");
        fixture(&second, "Two");
        catalog(&database, &id, &first);
        let original = fs::read(&first).unwrap();
        let first_response = handle_request(&database, &request(&id, "http://tauri.localhost"));
        assert_eq!(first_response.body(), &original);
        Connection::open(&database)
            .unwrap()
            .execute(
                "UPDATE books SET source_path = ?1 WHERE id = ?2",
                rusqlite::params![second.to_string_lossy(), id],
            )
            .unwrap();
        let second_response = handle_request(&database, &request(&id, "http://tauri.localhost"));
        assert_eq!(second_response.body(), &fs::read(&second).unwrap());
        Connection::open(&database)
            .unwrap()
            .execute("DELETE FROM books WHERE id = ?1", [&id])
            .unwrap();
        assert_eq!(
            handle_request(&database, &request(&id, "http://tauri.localhost")).status(),
            StatusCode::NOT_FOUND
        );
        assert_eq!(fs::read(&first).unwrap(), original);
    }

    #[test]
    #[ignore = "reads only explicitly selected external EPUB samples"]
    fn real_corpus_content_smoke() {
        let samples = std::env::var("KOMORI_EPUB_SAMPLES").expect("set sample EPUB paths");
        let directory = tempdir().unwrap();
        for (index, path) in samples.split('|').enumerate() {
            let source = Path::new(path);
            let before = Sha256::digest(fs::read(source).unwrap());
            let database = directory.path().join(format!("sample-{index}.sqlite3"));
            let id = Uuid::new_v4().to_string();
            catalog(&database, &id, source);
            assert_eq!(prepare(&database, &id).status, ContentStatus::Ready);
            let served = handle_request(&database, &request(&id, "http://tauri.localhost"));
            assert_eq!(served.status(), StatusCode::OK);
            assert_eq!(Sha256::digest(served.body()), before);
            assert_eq!(Sha256::digest(fs::read(source).unwrap()), before);
            println!(
                "sample {index}: {} bytes; source SHA-256 unchanged",
                served.body().len()
            );
        }
    }

    #[test]
    #[ignore = "reads one available record from an explicitly selected Library database"]
    fn real_library_content_smoke() {
        let database = std::env::var("KOMORI_LIBRARY_DATABASE").expect("set Library database");
        let connection =
            Connection::open_with_flags(&database, OpenFlags::SQLITE_OPEN_READ_ONLY).unwrap();
        let records = connection
            .prepare("SELECT id, source_path FROM books ORDER BY imported_at DESC")
            .unwrap()
            .query_map([], |row| {
                Ok((row.get::<_, String>(0)?, row.get::<_, String>(1)?))
            })
            .unwrap()
            .collect::<Result<Vec<_>, _>>()
            .unwrap();
        let (id, source) = records
            .into_iter()
            .find(|(_, source)| Path::new(source).is_file())
            .expect("Library needs an available EPUB record");
        let before = Sha256::digest(fs::read(&source).unwrap());
        let access = prepare(Path::new(&database), &id);
        assert_eq!(access.status, ContentStatus::Ready);
        assert!(!serde_json::to_string(&access).unwrap().contains(&source));
        let served = handle_request(
            Path::new(&database),
            &request(&id, "http://tauri.localhost"),
        );
        assert_eq!(served.status(), StatusCode::OK);
        assert_eq!(Sha256::digest(served.body()), before);
        assert_eq!(Sha256::digest(fs::read(&source).unwrap()), before);
        println!(
            "Library catalog ID {id}: {} bytes; source SHA-256 unchanged",
            served.body().len()
        );
    }
}
