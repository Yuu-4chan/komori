interface BrandMarkProps {
  className?: string;
}

// Komori's own static logo, inlined so its colors can follow the application theme.
const markup = logo.replace(/^<\?xml[^>]*>\s*/u, "");

/** Komori's logo, the book with cat ears also used for the application icon. */
export function BrandMark({ className }: BrandMarkProps) {
  return (
    <span
      className={["brand-mark", className].filter(Boolean).join(" ")}
      aria-hidden="true"
      dangerouslySetInnerHTML={{ __html: markup }}
    />
  );
}
